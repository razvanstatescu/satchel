// Builds src/lib/og-fonts.generated.ts: TTF subsets of the brand faces for the social card image routes
// (/s/[id]/opengraph-image, /s/[id]/twitter-image; A1). next/og (satori) draws text with real system fonts only when
// none are supplied, so every renderer must get the same glyphs — but satori's bundled font loader only decodes
// sfnt (ttf/otf) and woff, never woff2 (unlike src/lib/card-fonts.generated.ts, which is woff2 for the inline SVG
// media). Static instances (no variable axes left), only the glyphs the OG card can draw.
//
//   pnpm --filter web fonts:og            (needs network once; sources are cached and sha256-checked)
//
// Sources: google/fonts at the SAME pinned commits as build-card-fonts.mjs, SIL Open Font License 1.1 (subsetting
// and embedding are allowed; the OFL notice travels in the generated file). Output is deterministic: re-running it
// must not change the file.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import subsetFont from "subset-font";

const root = new URL("..", import.meta.url).pathname;
const out = join(root, "src/lib/og-fonts.generated.ts");
const cacheDir = process.env.CARD_FONT_CACHE ?? join(tmpdir(), "satchel-card-fonts");

const SOURCES = {
  funnel: {
    name: "Funnel Display",
    url: "https://raw.githubusercontent.com/google/fonts/f788e4777244983204dfd364d6dca2a1fab7d6b8/ofl/funneldisplay/FunnelDisplay%5Bwght%5D.ttf",
    sha256: "b4151c9c4b7b07eb74320096b4ff4156cca8821f5adfab34af9fd9a2d6c1179d",
    copyright: "Copyright 2023 The Funnel Project Authors (https://github.com/Dicotype/Funnel)",
  },
  onest: {
    name: "Onest",
    url: "https://raw.githubusercontent.com/google/fonts/4c1db3aec83c67dd223dd82a68c039cab30917a9/ofl/onest/Onest%5Bwght%5D.ttf",
    sha256: "966c5c29b4755da84b6854d5c21dd4eaa2420225d0e9874de602de176d4a9f31",
    copyright: "Copyright 2021 The Onest Project Authors (https://github.com/simpals/onest)",
  },
};

const uniq = (s) => [...new Set([...s])].sort().join("");

// Every string the OG card can draw (src/lib/og.ts; copy.pill, copy.buy.forSale, copy.card.ogClean, copy.card.svgSigs,
// the tickers, copy.app.badge). test/unit/og.test.ts checks that these cover what buildOgCardProps actually produces.
const LABEL_WORDS = ["Active", "Signing", "For sale", "Needs attention", "Clean history", "signature", "signatures", "BTC", "ETH", "SOL", "Testnet"];
const DIGITS = "0123456789";
const PUNCT = " .,<-#";

const FACES = [
  { key: "display", family: "Satchel OG Display", source: "funnel", weight: 800, axes: { wght: 800 }, chars: uniq(`Satchel #${DIGITS}`) },
  { key: "label", family: "Satchel OG Label", source: "onest", weight: 600, axes: { wght: 600 }, chars: uniq(LABEL_WORDS.join(" ") + DIGITS + PUNCT) },
];

const sha = (b) => createHash("sha256").update(b).digest("hex");

async function source(name) {
  const s = SOURCES[name];
  mkdirSync(cacheDir, { recursive: true });
  const p = join(cacheDir, `${name}-${s.sha256.slice(0, 12)}.ttf`);
  let buf = existsSync(p) ? readFileSync(p) : null;
  if (!buf) {
    const r = await fetch(s.url);
    if (!r.ok) throw new Error(`${name}: HTTP ${r.status}`);
    buf = Buffer.from(await r.arrayBuffer());
    writeFileSync(p, buf);
  }
  if (sha(buf) !== s.sha256) throw new Error(`${name}: sha256 mismatch (got ${sha(buf)})`);
  return buf;
}

const faces = [];
for (const f of FACES) {
  const ttf = await source(f.source);
  const subset = await subsetFont(ttf, f.chars, { targetFormat: "truetype", variationAxes: f.axes });
  faces.push({ ...f, bytes: subset.length, sha256: sha(subset), base64: subset.toString("base64") });
  console.log(`${f.key.padEnd(8)} ${f.family.padEnd(20)} ${String(subset.length).padStart(6)} B  ${f.chars.length} chars`);
}

const lines = [
  "// GENERATED by scripts/build-og-fonts.mjs. Do not edit by hand; run `pnpm --filter web fonts:og`.",
  "//",
  "// TTF subsets (static instances) of the Satchel 2.0 brand faces for the social card images (A1:",
  "// /s/[id]/opengraph-image, /s/[id]/twitter-image). satori (next/og) needs sfnt/woff, never woff2.",
  ...faces.map((f) => `//   ${f.family}: ${SOURCES[f.source].name} ${JSON.stringify(f.axes)}, ${f.bytes} B`),
  "//",
  `// ${SOURCES.funnel.copyright}`,
  `// ${SOURCES.onest.copyright}`,
  "// This Font Software is licensed under the SIL Open Font License, Version 1.1 (https://openfontlicense.org).",
  "// No Reserved Font Name is declared. The CSS families are \"Satchel OG …\" so an installed copy never substitutes.",
  "",
  "export interface OgFontFace {",
  "  family: string;",
  "  weight: number;",
  "  chars: string;",
  "  bytes: number;",
  "  sha256: string;",
  "  ttfBase64: string;",
  "}",
  "",
  "export const OG_FONTS = {",
  ...faces.map((f) => `  ${f.key}: { family: ${JSON.stringify(f.family)}, weight: ${f.weight}, chars: ${JSON.stringify(f.chars)}, bytes: ${f.bytes}, sha256: ${JSON.stringify(f.sha256)}, ttfBase64: ${JSON.stringify(f.base64)} },`),
  "} as const satisfies Record<string, OgFontFace>;",
  "",
];
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${out}`);
