//! SOL classifier (spec §5.9): a LEGACY message with a single signer and exactly one System Transfer.
//! Order (R-24): length → version → full parse (header, then structure) → durable-nonce scan → instruction rule.

use crate::errors::*;

pub const SOL_MAX_MESSAGE_BYTES: usize = 1232;
const SYSTEM_PROGRAM: [u8; 32] = [0u8; 32];
const IX_TRANSFER: [u8; 4] = [2, 0, 0, 0];
const IX_ADVANCE_NONCE: [u8; 4] = [4, 0, 0, 0];

#[derive(Debug, PartialEq, Eq)]
pub struct SolTransfer {
    pub recent_blockhash: [u8; 32],
    pub lamports: u64,
}

struct Ix<'a> {
    program: usize,
    accounts: &'a [u8],
    data: &'a [u8],
}

/// Canonical compact-u16 (1–3 bytes, 7 bits each; no redundant trailing zero byte; ≤ u16::MAX).
fn compact_u16(b: &[u8], pos: &mut usize) -> Result<usize, &'static str> {
    let mut val: usize = 0;
    for i in 0..3 {
        let byte = *b.get(*pos).ok_or(ERR_SOL_MALFORMED)?;
        *pos += 1;
        if i == 2 && byte > 0x03 {
            return Err(ERR_SOL_MALFORMED);
        }
        val |= ((byte & 0x7f) as usize) << (7 * i);
        if byte & 0x80 == 0 {
            if i > 0 && byte == 0 {
                return Err(ERR_SOL_MALFORMED); // non-canonical
            }
            return Ok(val);
        }
    }
    Err(ERR_SOL_MALFORMED)
}

fn take<'a>(b: &'a [u8], pos: &mut usize, n: usize) -> Result<&'a [u8], &'static str> {
    let end = pos.checked_add(n).ok_or(ERR_SOL_MALFORMED)?;
    let s = b.get(*pos..end).ok_or(ERR_SOL_MALFORMED)?;
    *pos = end;
    Ok(s)
}

pub fn classify(m: &[u8]) -> Result<SolTransfer, &'static str> {
    if m.len() > SOL_MAX_MESSAGE_BYTES {
        return Err(ERR_SOL_TOO_LONG);
    }
    let first = *m.first().ok_or(ERR_SOL_MALFORMED)?;
    if first >= 0x80 {
        return Err(ERR_SOL_VERSION);
    }
    let mut pos = 0usize;
    let header = take(m, &mut pos, 3)?;
    let (num_signers, ro_signed, ro_unsigned) = (header[0] as usize, header[1], header[2] as usize);
    if num_signers != 1 || ro_signed != 0 {
        return Err(ERR_SOL_HEADER);
    }
    let num_keys = compact_u16(m, &mut pos)?;
    if !(2..=16).contains(&num_keys) || num_signers + ro_unsigned > num_keys {
        return Err(ERR_SOL_MALFORMED);
    }
    let keys = take(m, &mut pos, 32 * num_keys)?;
    let key = |i: usize| &keys[32 * i..32 * i + 32];
    let mut recent_blockhash = [0u8; 32];
    recent_blockhash.copy_from_slice(take(m, &mut pos, 32)?);
    let num_ix = compact_u16(m, &mut pos)?;
    let mut ixs: Vec<Ix> = Vec::new();
    for _ in 0..num_ix {
        let program = *take(m, &mut pos, 1)?.first().ok_or(ERR_SOL_MALFORMED)? as usize;
        if program >= num_keys {
            return Err(ERR_SOL_MALFORMED);
        }
        let na = compact_u16(m, &mut pos)?;
        let accounts = take(m, &mut pos, na)?;
        if accounts.iter().any(|a| (*a as usize) >= num_keys) {
            return Err(ERR_SOL_MALFORMED);
        }
        let nd = compact_u16(m, &mut pos)?;
        let data = take(m, &mut pos, nd)?;
        ixs.push(Ix { program, accounts, data });
    }
    if pos != m.len() {
        return Err(ERR_SOL_MALFORMED); // trailing bytes
    }
    // 4. durable-nonce scan over EVERY instruction, before the count rule.
    if ixs.iter().any(|ix| key(ix.program) == SYSTEM_PROGRAM && ix.data.len() >= 4 && ix.data[0..4] == IX_ADVANCE_NONCE) {
        return Err(ERR_SOL_DURABLE_NONCE);
    }
    // 5. exactly one System Transfer from the signer.
    if ixs.len() != 1 {
        return Err(ERR_SOL_INSTRUCTION);
    }
    let ix = &ixs[0];
    if key(ix.program) != SYSTEM_PROGRAM || ix.data.len() != 12 || ix.data[0..4] != IX_TRANSFER || ix.accounts.len() != 2 || ix.accounts[0] != 0 {
        return Err(ERR_SOL_INSTRUCTION);
    }
    let mut l = [0u8; 8];
    l.copy_from_slice(&ix.data[4..12]);
    Ok(SolTransfer { recent_blockhash, lamports: u64::from_le_bytes(l) })
}

