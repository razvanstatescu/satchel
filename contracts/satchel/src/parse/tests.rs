//! Classifier-level tests: hashing (INV-07 unit half), event bytes, and the shared vectors in `vectors/*.json`
//! (format: docs/handoff/core.md §1).

use super::*;
use crate::errors::*;
use near_sdk::serde_json::{self, Value};

fn evm_req(h: &str) -> SignRequest {
    SignRequest::Evm { unsigned_tx: h.into() }
}

#[test]
fn evm_payload_is_keccak_of_exact_bytes() {
    let c = classify(&evm_req(&["0x", evm::tests::KB31_TX].concat())).unwrap();
    assert_eq!(c.chain, Chain::Evm);
    assert_eq!(c.items.len(), 1);
    assert_eq!(hex::encode(&c.items[0].record_payload), evm::tests::KB31_HASH);
    assert_eq!(c.items[0].mpc_payload, MpcPayload::Ecdsa(evm::tests::KB31_HASH.into()));
    assert_eq!(hex::encode(&c.preimages[0]), evm::tests::KB31_TX);
    match &c.items[0].detail {
        SigDetail::Evm { chain_id, nonce, unsigned_tx } => {
            assert_eq!((*chain_id, *nonce), (11_155_111, 0));
            assert_eq!(hex::encode(unsigned_tx), evm::tests::KB31_TX);
        }
        d => panic!("{d:?}"),
    }
    // uppercase input, same hash
    let c2 = classify(&evm_req(&evm::tests::KB70_F1_TX.to_uppercase())).unwrap();
    assert_eq!(hex::encode(&c2.items[0].record_payload), evm::tests::KB70_F1_HASH);
}

#[test]
fn btc_payloads_are_sha256d_per_input() {
    let req = SignRequest::Btc {
        preimages: vec![btc::tests::BJS_PRE0.into(), btc::tests::BJS_PRE1.into()],
        outputs: btc::tests::BJS_OUTPUTS.into(),
    };
    assert_eq!(request_count(&req), 2);
    let c = classify(&req).unwrap();
    assert_eq!(c.items.len(), 2);
    assert_eq!(c.items[0].mpc_payload, MpcPayload::Ecdsa(btc::tests::BJS_H0.into()));
    assert_eq!(c.items[1].mpc_payload, MpcPayload::Ecdsa(btc::tests::BJS_H1.into()));
    assert_eq!(hex::encode(&c.btc_outputs.unwrap()), btc::tests::BJS_OUTPUTS);
    assert_eq!(c.items[1].detail, SigDetail::Btc { txid: [0x22; 32], vout: 0, amount_sats: 20_000 });
}

#[test]
fn sol_payload_is_message_and_record_is_sha256() {
    let m = sol::tests::W3_TRANSFER;
    let c = classify(&SignRequest::Sol { message: m.into() }).unwrap();
    assert_eq!(c.items[0].mpc_payload, MpcPayload::Eddsa(m.into()));
    assert_eq!(c.items[0].record_payload, near_sdk::env::sha256_array(hex::decode(m).unwrap()));
    assert_eq!(c.items[0].detail, SigDetail::Sol { recent_blockhash: [9; 32], lamports: 1_000_000 });
}

#[test]
fn hex_and_count_errors() {
    assert_eq!(classify(&evm_req("02e")), Err(ERR_HEX));
    assert_eq!(classify(&SignRequest::Sol { message: "zz".into() }), Err(ERR_HEX));
    assert_eq!(classify(&SignRequest::Btc { preimages: vec![], outputs: "".into() }), Err(ERR_BTC_INPUT_COUNT));
    assert_eq!(
        classify(&SignRequest::Btc { preimages: vec!["00".into(); 11], outputs: "zz".into() }),
        Err(ERR_BTC_INPUT_COUNT),
        "count is checked before hex"
    );
    assert_eq!(classify(&SignRequest::Btc { preimages: vec!["0".into()], outputs: "".into() }), Err(ERR_HEX));
    assert_eq!(classify(&SignRequest::Btc { preimages: vec![btc::tests::BJS_PRE0.into()], outputs: "0".into() }), Err(ERR_HEX));
}

#[test]
fn sign_request_json_shapes() {
    let r: SignRequest = serde_json::from_str(r#"{"evm":{"unsigned_tx":"02"}}"#).unwrap();
    assert!(matches!(r, SignRequest::Evm { .. }));
    let r: SignRequest = serde_json::from_str(r#"{"btc":{"preimages":["00","11"],"outputs":"22"}}"#).unwrap();
    assert_eq!(request_count(&r), 2);
    let r: SignRequest = serde_json::from_str(r#"{"sol":{"message":"01"}}"#).unwrap();
    assert!(matches!(r, SignRequest::Sol { .. }));
}

// ── shared vectors (vectors/{evm,btc,sol}.json, generated by the `core` agent) ─────────────────────

fn vectors_dir() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../vectors")
}

fn str_field<'a>(v: &'a Value, k: &str) -> Option<&'a str> {
    v.get(k).and_then(Value::as_str)
}

fn dec(v: &Value) -> Option<u128> {
    match v {
        Value::String(s) => s.parse().ok(),
        Value::Number(n) => n.as_u64().map(u128::from),
        _ => None,
    }
}

/// Runs one vector; returns a failure description or None.
fn run_vector(set: &str, v: &Value) -> Option<String> {
    let name = str_field(v, "name").unwrap_or("?").to_string();
    let req: SignRequest = match v.get("request").map(|r| serde_json::from_value(r.clone())) {
        Some(Ok(r)) => r,
        Some(Err(e)) => return Some(format!("{set}/{name}: request does not deserialize: {e}")),
        None => return Some(format!("{set}/{name}: no `request`")),
    };
    let expect = &v["expect"];
    let ok = expect["ok"].as_bool().unwrap_or(false);
    // `state.evm_max_nonce` (decimal string, or null/absent = the token has no EVM record): `sign_for`'s nonce-gap
    // rule (spec §5.9, D-43) runs after the stateless classifier, exactly as in `sign_for`.
    let max_signed = match v.get("state").and_then(|s| s.get("evm_max_nonce")) {
        None | Some(Value::Null) => None,
        Some(x) => match dec(x) {
            Some(n) if n < u64::MAX as u128 => Some(n as u64),
            _ => return Some(format!("{set}/{name}: bad state.evm_max_nonce {x}")),
        },
    };
    let got = classify(&req).and_then(|c| match &c.items[0].detail {
        SigDetail::Evm { nonce, .. } => evm::check_nonce(*nonce, max_signed).map(|_| c),
        _ => Ok(c),
    });
    match (ok, &got) {
        (false, Err(code)) => {
            let want = str_field(expect, "error").unwrap_or("");
            (want != *code).then(|| format!("{set}/{name}: want {want}, got {code}"))
        }
        (false, Ok(_)) => Some(format!("{set}/{name}: accepted, want {:?}", str_field(expect, "error"))),
        (true, Err(code)) => Some(format!("{set}/{name}: refused with {code}, want ok")),
        (true, Ok(c)) => check_accepted(set, &name, expect, c),
    }
}

fn check_accepted(set: &str, name: &str, expect: &Value, c: &Classified) -> Option<String> {
    let fail = |m: String| Some(format!("{set}/{name}: {m}"));
    let hashes: Vec<String> = c.items.iter().map(|i| hex::encode(&i.record_payload)).collect();
    if let Some(h) = str_field(expect, "hash")
        && hashes.first().map(String::as_str) != Some(h) {
            return fail(format!("hash {h} != {:?}", hashes.first()));
        }
    if let Some(hs) = expect.get("hashes").and_then(Value::as_array) {
        let want: Vec<&str> = hs.iter().filter_map(Value::as_str).collect();
        if want != hashes.iter().map(String::as_str).collect::<Vec<_>>() {
            return fail(format!("hashes {want:?} != {hashes:?}"));
        }
    }
    if let Some(mpc) = expect.get("mpc").and_then(Value::as_array) {
        if mpc.len() != c.items.len() {
            return fail(format!("mpc count {} != {}", mpc.len(), c.items.len()));
        }
        for (m, it) in mpc.iter().zip(&c.items) {
            let got = serde_json::to_value(&it.mpc_payload).unwrap();
            if m.get("payload_v2") != Some(&got) {
                return fail(format!("payload_v2 {:?} != {got}", m.get("payload_v2")));
            }
            if m.get("domain_id").and_then(Value::as_u64) != Some(c.chain.domain_id()) {
                return fail("domain_id".into());
            }
            if str_field(m, "path_chain") != Some(c.chain.slug()) {
                return fail("path_chain".into());
            }
        }
    }
    let f = &expect["fields"];
    if f.is_null() {
        return None;
    }
    match (c.chain, &c.items[0].detail) {
        (Chain::Evm, SigDetail::Evm { chain_id, nonce, unsigned_tx }) => {
            if dec(&f["chain_id"]) != Some(*chain_id as u128) || dec(&f["nonce"]) != Some(*nonce as u128) {
                return fail(format!("evm fields chain_id/nonce {f}"));
            }
            if let Some(u) = str_field(f, "unsigned_tx")
                && u != hex::encode(unsigned_tx) {
                    return fail("unsigned_tx".into());
                }
            // C2: the view's `erc20` (token, recipient, amount) must equal what the contract derives from the bytes
            let want = f.get("erc20").filter(|e| !e.is_null());
            match (evm::erc20_of(unsigned_tx), want) {
                (None, None) => {}
                (Some(e), Some(w))
                    if str_field(w, "token") == Some(&hex::encode(&e.token))
                        && str_field(w, "to") == Some(&hex::encode(&e.to))
                        && dec(&w["amount"]) == Some(e.amount) => {}
                (got, _) => return fail(format!("erc20 {got:?} vs {f}")),
            }
        }
        (Chain::Evm, SigDetail::EvmMessage { message }) | (Chain::Sol, SigDetail::SolMessage { message }) => {
            if str_field(f, "message") != Some(&hex::encode(message)) || str_field(f, "signed_bytes") != Some(&hex::encode(&c.preimages[0])) {
                return fail(format!("message fields {f}"));
            }
        }
        (Chain::Btc, _) => {
            let inputs = f["inputs"].as_array().cloned().unwrap_or_default();
            if inputs.len() != c.items.len() {
                return fail("btc input count".into());
            }
            for (fi, it) in inputs.iter().zip(&c.items) {
                let SigDetail::Btc { txid, vout, amount_sats } = &it.detail else { return fail("detail".into()) };
                if str_field(fi, "txid") != Some(&hex::encode(txid))
                    || fi["vout"].as_u64() != Some(*vout as u64)
                    || dec(&fi["amount_sats"]) != Some(*amount_sats as u128)
                {
                    return fail(format!("btc input {fi}"));
                }
            }
        }
        (Chain::Sol, SigDetail::Sol { recent_blockhash, lamports }) => {
            if str_field(f, "recent_blockhash") != Some(&hex::encode(recent_blockhash)) || dec(&f["lamports"]) != Some(*lamports as u128) {
                return fail(format!("sol fields {f}"));
            }
        }
        _ => return fail("chain/detail mismatch".into()),
    }
    None
}

/// Runs every vector in vectors/{evm,btc,sol}.json through the classifiers. Missing files are reported and skipped
/// (the `core` agent generates them); a present file must be well-formed and every vector must pass.
#[test]
fn shared_vectors() {
    let mut failures = vec![];
    let mut ran = 0;
    for set in ["evm", "btc", "sol", "msg"] {
        let path = vectors_dir().join(format!("{set}.json"));
        let Ok(text) = std::fs::read_to_string(&path) else {
            eprintln!("shared_vectors: {} not present yet, skipped", path.display());
            continue;
        };
        let doc: Value = serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        let vectors = doc["vectors"].as_array().unwrap_or_else(|| panic!("{}: no `vectors` array", path.display()));
        assert!(!vectors.is_empty(), "{set}: empty vector set");
        for v in vectors {
            ran += 1;
            if let Some(f) = run_vector(set, v) {
                failures.push(f);
            }
        }
    }
    eprintln!("shared_vectors: ran {ran} vectors, {} failures", failures.len());
    assert!(failures.is_empty(), "vector failures:\n{}", failures.join("\n"));
}
